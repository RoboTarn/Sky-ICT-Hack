async (page) => {
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  const commander='https://commander-aigcs-skyhack.robotarn.org';
  const crewBase='https://crew-aigcs-skyhack.robotarn.org';
  await page.goto(commander);
  await page.setViewportSize({width:1536,height:1100});
  await page.getByRole('heading',{name:'ศูนย์ควบคุมภาคพื้น'}).waitFor({timeout:30000});
  await page.getByRole('button',{name:'เริ่มรอบใหม่',exact:true}).click();
  await page.getByRole('button',{name:'จำลองเหตุการณ์',exact:true}).click();
  await page.getByRole('button',{name:'สร้างเหตุการณ์',exact:true}).click();
  const approval=page.getByRole('button',{name:'อนุมัติและส่งทีม',exact:true});
  await approval.waitFor({timeout:60000});
  await page.waitForFunction(()=>{
    const b=[...document.querySelectorAll('button')].find(b=>b.textContent==='อนุมัติและส่งทีม');
    return b&&!b.disabled;
  });
  await page.getByRole('button',{name:/^แผน 1/}).click();
  const crew=await page.context().newPage();
  crew.on('pageerror',e=>errors.push(e.message));
  await crew.goto(crewBase);
  await crew.setViewportSize({width:414,height:1000});
  await crew.getByRole('heading',{name:'วันนี้คุณอยู่ทีมไหน?'}).waitFor({timeout:30000});
  await crew.getByRole('textbox',{name:'ค้นหาสมาชิก'}).fill('A17');
  await crew.getByRole('button',{name:/มินตรา/}).click();
  await crew.getByRole('link',{name:'เข้าสู่ mission',exact:true}).click();
  await crew.getByRole('heading',{name:'สวัสดี มินตรา'}).waitFor({timeout:30000});
  const response=page.waitForResponse(r=>r.url().endsWith('/approve')&&r.request().method()==='POST');
  await approval.click(); await response;
  const began=Date.now();
  await crew.getByRole('button',{name:'รับ mission',exact:true}).waitFor({timeout:5000});
  const syncMs=Date.now()-began;
  await crew.getByRole('button',{name:'รับ mission',exact:true}).click();
  await crew.getByRole('button',{name:'ออกเดินทาง',exact:true}).waitFor();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'output/playwright/hosted-commander.png'});
  await crew.screenshot({path:'output/playwright/hosted-crew.png',fullPage:true});
  await page.getByRole('button',{name:'จำลองเหตุการณ์',exact:true}).click();
  await page.getByRole('button',{name:/^พบควัน \/ ไฟ/}).click();
  await page.getByRole('button',{name:'สร้างเหตุการณ์',exact:true}).click();
  const alert=page.getByRole('alertdialog');
  await alert.waitFor({timeout:10000});
  await alert.getByRole('button',{name:'อนุมัติและส่งทีม',exact:true}).waitFor({timeout:60000});
  await alert.locator('.auto-analysis').waitFor({state:'hidden',timeout:60000});
  await alert.locator('.ai-reason').waitFor();
  await page.screenshot({path:'output/playwright/hosted-emergency.png'});
  const source=await alert.locator('.ai-reason b').textContent();
  await page.getByRole('button',{name:'รับทราบและปิดแจ้งเตือน',exact:true}).click();
  await page.getByRole('button',{name:'เริ่มรอบใหม่',exact:true}).click();
  await crew.goto(crewBase); await crew.getByRole('heading',{name:'วันนี้คุณอยู่ทีมไหน?'}).waitFor();
  if(errors.length) throw new Error(errors.join(';'));
  return {passed:true,commander:page.url(),crew:crew.url(),syncMs,emergency:true,source,pageErrors:errors};
}
